import { mkdir, readFile, copyFile, writeFile, readdir } from "node:fs/promises";
import { join } from "node:path";
import { randomUUID } from "node:crypto";
import { createRequire } from "node:module";
import { createClient } from "@supabase/supabase-js";
import { createServerClient } from "@supabase/ssr";
import sharp from "sharp";
import { test } from "@e2e-dev/web";
import { expect } from "e2e";
const parser = createRequire(import.meta.url)("vcard-parser");
const origin = "http://127.0.0.1:3137";
process.loadEnvFile(".env.local");

test("Contacts UX crop, override, cached photo, visibility and publication isolation", async ({ app, screen, browser }) => {
  if (new URL(app.baseUrl!).origin !== origin || process.env.NEXT_PUBLIC_SUPABASE_URL !== "https://flkakuysakgwfoemgbwn.supabase.co") throw new Error("Staging-only synthetic test");
  const client = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY!, { auth: { persistSession: false, autoRefreshToken: false } });
  const cookies: { name: string; value: string; domain: string; path: string }[] = [];
  const ssr = createServerClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY!, { cookies: { getAll: () => [], setAll: values => { for (const value of values) cookies.push({ name: value.name, value: value.value, domain: "127.0.0.1", path: "/" }); } } });
  const auth = { email: process.env.E2E_USER_OWNER_USERNAME!, password: process.env.E2E_USER_OWNER_PASSWORD! };
  if ((await client.auth.signInWithPassword(auth)).error || (await ssr.auth.signInWithPassword(auth)).error) throw new Error("Synthetic Staging owner sign-in failed");
  const bid = randomUUID(), pid = randomUUID(), asset = randomUUID();
  const slug = `contacts-ux-${Date.now().toString(36)}-${bid.slice(0, 6)}`;
  const owner = (await client.auth.getUser()).data.user!.id;
  const path = `${owner}/${bid}/${asset}.webp`, photoPath = path.replace(".webp", ".contact.jpg");
  const bucket = client.storage.from("business-media");
  const red = await sharp({ create: { width: 200, height: 200, channels: 3, background: "red" } }).png().toBuffer();
  const logo = await sharp({ create: { width: 400, height: 200, channels: 3, background: "blue" } }).composite([{ input: red, left: 0, top: 0 }]).webp().toBuffer();
  const photo = await sharp(logo).resize({ width: 384 }).jpeg().toBuffer();
  async function checked(result: { error: unknown }) { if (result.error) throw new Error("Synthetic Staging fixture operation failed"); }
  await checked(await client.from("businesses").insert({ id: bid, name: "Synthetic Contacts UX", category: "QA" }));
  await checked(await bucket.upload(path, logo, { contentType: "image/webp" }));
  await checked(await bucket.upload(photoPath, photo, { contentType: "image/jpeg" }));
  await checked(await client.from("media_assets").insert({ id: asset, business_id: bid, storage_path: path, contact_photo_path: photoPath, mime_type: "image/webp", size_bytes: logo.length }));
  const logoUrl = bucket.getPublicUrl(path).data.publicUrl;
  const fields = ["https://instagram.com/qa_one", "https://instagram.com/qa_two", "https://wa.me/201012345678", "https://www.instapay.me/i?address=qa%40instapay", "https://facebook.com/qa", "https://example.test"].map((value, index) => ({ id: `link-${index}`, kind: "custom", label: `Provider ${index}`, value, enabled: true }));
  const contact = { enabled: true, displayName: "Synthetic Contacts UX", organization: "QA", primaryPhone: "01012345678", fields: [...fields, { ...fields[0], id: "duplicate", kind: "social" }, { id: "phone", kind: "phone", label: "Second", value: "+442071234567", enabled: true }, { id: "hours", kind: "hours", label: "Hours", value: "9–5", enabled: true }] };
  await checked(await client.from("business_pages").insert({ id: pid, business_id: bid, slug, template: "professional", contact_config: contact }));
  await checked(await client.from("page_sections").insert([{ page_id: pid, section_key: "hero", kind: "hero", title: "", position: 0, enabled: true, content: { logoUrl, language: "en" } }, { page_id: pid, section_key: "actions", kind: "quick_actions", title: "Actions", position: 1, enabled: true, content: { items: [{ id: "call", provider: "call", label: "Call", value: "01012345678" }] } }]));
  await checked(await client.rpc("publish_page", { target_page_id: pid }));
  const editor = `/admin/businesses/${bid}`;
  await browser.setCookies(cookies);
  await app.open(editor);
  const width = await browser.evaluate(() => innerWidth);
  const artifactPath = async (relative: string) => {
    const root = `.e2e/artifacts/${width}`;
    const paths = await readdir(root, { recursive: true });
    const found = paths.find(path => path.replaceAll("\\", "/").endsWith(relative.replaceAll("\\", "/")));
    if (!found) throw new Error(`Missing runner artifact: ${relative}`);
    return join(root, found);
  };
  const panel = browser.locator(".contact-card-editor");
  await expect(panel.getByRole("checkbox", "Show Download Contact Link")).toBeChecked();
  await expect(panel.getByLabel("Custom Contact Photo URL")).toHaveValue("");
  await expect(panel.getByRole("button", "Apply crop")).toBeEnabled();
  async function download() { const result = await browser.waitForDownload(() => panel.getByRole("button", "Test contact download").tap()); return readFile(await artifactPath(result.path), "utf8"); }
  const baseline = await (await fetch(`${origin}/b/${slug}/contact.vcf`)).text();
  const parsed = parser.parse(baseline.replace(/\r\n /g, ""));
  expect(parsed.url).toHaveLength(6); expect(parsed.tel).toHaveLength(2); expect(parsed.note[0].value).toBe("Hours: 9–5");
  expect(baseline).toContain("PHOTO;ENCODING=b;TYPE=JPEG:");
  await panel.getByLabel("Zoom", { exact: true }).focus();
  await browser.keyboard.press("End");
  await panel.getByLabel("Horizontal position").focus();
  await browser.keyboard.press("End");
  await panel.getByLabel("Vertical position").focus();
  await browser.keyboard.press("Home");
  await panel.getByRole("button", "Reset", { exact: true }).tap();
  await expect(panel.getByLabel("Zoom", { exact: true })).toHaveValue("1000");
  await panel.getByLabel("Zoom", { exact: true }).focus(); await browser.keyboard.press("End");
  await browser.locator(".contact-crop-stage").scrollIntoView();
  const rect = await browser.evaluate(() => { const r = document.querySelector(".contact-crop-stage")!.getBoundingClientRect(); return { x: r.x + 120, y: r.y + 120 }; });
  await browser.mouse.move(rect.x, rect.y); await browser.mouse.down(); await browser.mouse.move(rect.x - 35, rect.y - 25); await browser.mouse.up();
  expect(await panel.getByLabel("Horizontal position").inputValue()).not.toBe("500");
  await panel.getByRole("button", "Apply crop").tap();
  await panel.getByRole("checkbox", "Show Download Contact Link").uncheck();
  await expect(browser.locator(".editor-phone-screen .contact-download-fallback")).toHaveCount(0);
  await expect(browser.locator(".editor-phone-screen .contact-download-button")).toHaveCount(1);
  const cropped = await download(); expect(cropped).not.toBe(baseline);
  const photoMatch = cropped.replace(/\r\n /g, "").match(/PHOTO;ENCODING=b;TYPE=JPEG:([^\r]+)/);
  expect(Boolean(photoMatch)).toBe(true);
  const croppedMetadata = await sharp(Buffer.from(photoMatch![1], "base64")).metadata();
  expect(croppedMetadata.width).toBe(croppedMetadata.height);
  expect(croppedMetadata.format).toBe("jpeg");
  await screen.getByRole("button", "Save draft", { exact: true }).tap();
  await expect(browser.locator(".editor-save-status")).toHaveText("Draft saved", { timeout: 30000 });
  expect(await (await fetch(`${origin}/b/${slug}/contact.vcf`)).text()).toBe(baseline);
  await browser.reload();
  await expect(panel.getByRole("checkbox", "Show Download Contact Link")).not.toBeChecked();
  await expect(panel.getByLabel("Zoom", { exact: true })).toHaveValue("4000");
  expect(await download()).toBe(cropped);
  const objectsBefore = (await bucket.list(`${owner}/${bid}`)).data!.length;
  expect(await download()).toBe(cropped);
  expect((await bucket.list(`${owner}/${bid}`)).data!.length).toBe(objectsBefore);
  await screen.getByRole("button", "Publish", { exact: true }).tap();
  await expect(browser.locator(".editor-save-status")).toHaveText("Published", { timeout: 30000 });
  expect(await (await fetch(`${origin}/b/${slug}/contact.vcf`)).text()).toBe(cropped);
  expect((await client.from("page_sections").select("content").eq("page_id", pid).eq("kind", "hero").single()).data!.content.logoUrl).toBe(logoUrl);
  expect(Buffer.from(await (await bucket.download(path)).data!.arrayBuffer()).equals(logo)).toBe(true);
  const dir = "artifacts/contacts-ux"; await mkdir(dir, { recursive: true });
  const capture = async (label: string) => { await copyFile(await artifactPath(await app.screenshot(label)), `${dir}/${width}-${label}.png`); };
  await expect(panel.getByRole("button", "Apply crop")).toBeEnabled();
  await browser.locator(".contact-photo-editor").scrollIntoView(); await capture("crop-editor");
  await app.open(`/b/${slug}`);
  await expect(browser.locator(".contact-download-fallback")).toHaveCount(0);
  const primary = await browser.waitForDownload(() => browser.locator(".contact-download-button").tap());
  expect(await readFile(await artifactPath(primary.path), "utf8")).toBe(cropped);
  await capture("published-hidden");
  await app.open(editor);
  const blue = await sharp({ create: { width: 160, height: 160, channels: 3, background: "green" } }).png().toBuffer();
  const customFile = `${dir}/custom-${width}.png`; await writeFile(customFile, blue);
  await panel.getByLabel("Upload custom contact photo", { exact: true }).setInputFiles(customFile);
  await expect(panel.getByLabel("Custom Contact Photo URL")).toHaveValue(/business-media/);
  const overridden = await download(); expect(overridden).not.toBe(cropped);
  await screen.getByRole("button", "Publish", { exact: true }).tap(); await expect(browser.locator(".editor-save-status")).toHaveText("Published", { timeout: 30000 });
  expect(await (await fetch(`${origin}/b/${slug}/contact.vcf`)).text()).toBe(overridden);
  await panel.getByRole("button", "Remove custom contact photo").tap();
  await panel.getByRole("checkbox", "Show Download Contact Link").check();
  await expect(browser.locator(".editor-phone-screen .contact-download-fallback")).toHaveCount(1);
  expect(await download()).toBe(baseline);
  await screen.getByRole("button", "Publish", { exact: true }).tap(); await expect(browser.locator(".editor-save-status")).toHaveText("Published", { timeout: 30000 });
  await expect.poll(async () => (await (await fetch(`${origin}/b/${slug}`)).text()).includes('class="contact-download-fallback"'), { timeout: 15000 }).toBe(true);
  await app.open(`/b/${slug}`);
  await expect(browser.locator(".contact-download-fallback")).toHaveCount(1);
  for (const selector of [".contact-download-button", ".contact-download-fallback"]) { const d = await browser.waitForDownload(() => browser.locator(selector).tap()); expect(await readFile(await artifactPath(d.path), "utf8")).toBe(baseline); }
  await capture("published-visible");
  await writeFile(`${dir}/fixture-${width}.json`, JSON.stringify({ businessId: bid, pageId: pid, slug, staging: true }, null, 2));
  await client.auth.signOut({ scope: "local" });
});
