import { test } from "@e2e-dev/web";
import { credentials, expect } from "e2e";
import fs from "node:fs/promises";
import { markDocument, expectSameDocument } from "./_helpers/document";

test("inventory filters preserve document, draft and explicit selection", async ({ app, screen, browser }) => {
  test.skip(!process.env.E2E_FIXTURE_PATH, "Requires namespaced owner fixture");
  const fixture = JSON.parse(await fs.readFile(process.env.E2E_FIXTURE_PATH!, "utf8"));
  await app.open("/login?lang=en");
  await screen.getByLabel("Email address").fill(credentials.user("owner").username);
  await screen.getByLabel("Password").fill(credentials.user("owner").password);
  await screen.getByRole("button", "Sign in securely").tap();
  await expect(browser).toHaveURL(/\/admin(?:\?.*)?$/);
  await app.open(`/admin/cards?batch=${fixture.batchId}`);
  await expect(browser.locator("tr[data-card-id]")).toHaveCount(1);
  await browser.locator('input[name="name"]').fill("Unsaved manufacturing name");
  await browser.locator('tr[data-card-id] input[type="checkbox"]').check();
  const before = await markDocument(browser);
  await screen.getByRole("button", "تطبيق التصفية").tap();
  await expect(browser.locator(".inventory-selection")).toBeVisible();
  await expect(browser.locator('input[name="name"]')).toHaveValue("Unsaved manufacturing name");
  await expect(browser.locator('tr[data-card-id] input[type="checkbox"]')).toBeChecked();
  await expectSameDocument(browser, before);
});

test("assignment and disable preserve document, history and unrelated work", async ({ app, screen, browser }) => {
  test.skip(process.env.E2E_ALLOW_MUTATIONS !== "true" || !process.env.E2E_FIXTURE_PATH, "Requires authorized synthetic mutation fixture");
  const fixture = JSON.parse(await fs.readFile(process.env.E2E_FIXTURE_PATH!, "utf8"));
  await app.open("/login?lang=en");
  await screen.getByLabel("Email address").fill(credentials.user("owner").username);
  await screen.getByLabel("Password").fill(credentials.user("owner").password);
  await screen.getByRole("button", "Sign in securely").tap();
  await expect(browser).toHaveURL(/\/admin(?:\?.*)?$/);
  await app.open(`/admin/cards?batch=${fixture.batchId}&page_search=${fixture.slug}`);
  const row = browser.locator("tr[data-card-id]");
  await expect(row).toHaveCount(1);
  await browser.locator('input[name="name"]').fill("Keep this draft");
  await browser.locator('tr[data-card-id] input[type="checkbox"]').check();
  await browser.locator("summary").tap();
  await expect(browser.locator("details[open]")).toBeVisible();
  const before = await markDocument(browser);
  await row.getByRole("button", "تفعيل / نقل").tap();
  await screen.getByRole("button", "إلغاء", { exact: true }).tap();
  await expectSameDocument(browser, before);
  await row.getByRole("button", "تفعيل / نقل").tap();
  await screen.getByRole("button", "تأكيد التعيين", { exact: true }).tap();
  await expect(browser.locator("[data-card-status]")).toHaveText("active");
  await expect(browser.locator(".card-assignment-form .mutation-result")).toBeVisible();
  await expect(browser.locator("details[open]")).toBeVisible();
  await expect(browser.locator('tr[data-card-id] input[type="checkbox"]')).toBeChecked();
  await expect(browser.locator('input[name="name"]')).toHaveValue("Keep this draft");
  await expectSameDocument(browser, before);
  await row.getByRole("button", "تعطيل", { exact: true }).tap();
  await screen.getByRole("button", "تعطيل البطاقة", { exact: true }).tap();
  await expect(browser.locator("[data-card-status]")).toHaveText("disabled");
  await expectSameDocument(browser, before);
  await app.open(`/admin/cards?batch=${fixture.batchId}`);
  await expect(browser.locator("[data-card-status]")).toHaveText("disabled");
});

