import { test } from "@e2e-dev/web";
import { credentials, expect } from "e2e";
import fs from "node:fs/promises";
import { markDocument, expectSameDocument } from "./_helpers/document";

test("delivery destinations survive save, preview, publication and override", async ({ app, screen, browser }) => {
  test.skip(process.env.E2E_ALLOW_MUTATIONS !== "true" || !process.env.E2E_FIXTURE_PATH, "Requires authorized namespaced fixture");
  const fixture = JSON.parse(await fs.readFile(process.env.E2E_FIXTURE_PATH!, "utf8"));
  await app.open("/login?lang=en");
  await screen.getByLabel("Email address").fill(credentials.user("owner").username);
  await screen.getByLabel("Password").fill(credentials.user("owner").password);
  await screen.getByRole("button", "Sign in securely").tap();
  await expect(browser).toHaveURL(/\/admin(?:\?.*)?$/);
  await app.open(`/admin/businesses/${fixture.businessId}`);
  await browser.locator(".navigator-item").filter({ hasText: "Quick Actions" }).tap();
  const suffix = Date.now().toString(36);
  const talabatLabel = `Talabat restaurant ${suffix}`, fastLabel = `Fast restaurant ${suffix}`, overrideLabel = `Fast branch ${suffix}`, inheritedLabel = `Fast default ${suffix}`;
  await screen.getByRole("button", "Ordering & delivery", { exact: true }).tap();
  await screen.getByRole("button", "Add Talabat", { exact: true }).tap();
  const rows = browser.locator(".editor-form-pane > .live-items-editor > .live-item-row");
  const talabat = rows.last();
  await talabat.getByLabel("Button label", { exact: true }).fill(talabatLabel);
  const destination = "https://www.talabat.com/egypt/taboon-zamalek?source=nextap%2Fqa#menu";
  await talabat.getByLabel(/Destination URL/).fill(destination);
  await screen.getByRole("button", "Add Fast App", { exact: true }).tap();
  await rows.last().getByLabel("Button label", { exact: true }).fill(fastLabel);
  // A synthetic public-page destination verifies exact persistence and transport;
  // it is not evidence of a provider-supported customer URL or device handoff.
  const fastDestination = "https://merchant.example.test/restaurant?share=a%2Fb#menu";
  await rows.last().getByLabel(/Destination URL/).fill(fastDestination);
  await screen.getByRole("button", "Add Fast App", { exact: true }).tap();
  await rows.last().getByLabel("Button label", { exact: true }).fill(overrideLabel);
  await browser.evaluate(label => {
    const row = [...document.querySelectorAll('.editor-form-pane .live-item-row')].find(candidate => candidate.querySelector<HTMLInputElement>('input[name$=".label"]')?.value === label);
    if (!row) throw new Error("Destination row missing");
    const select = row.querySelector<HTMLSelectElement>('select');
    if (!select) throw new Error("Destination source selector missing");
    select.value = "override";
    select.dispatchEvent(new Event("change", { bubbles: true }));
    return true;
  }, overrideLabel);
  const overrideDestination = "https://merchant.example.test/branch?ref=nextap%2Fqa";
  await rows.last().getByLabel(/Destination URL/).fill(overrideDestination);
  await screen.getByRole("button", "Add Fast App", { exact: true }).tap();
  await rows.last().getByLabel("Button label", { exact: true }).fill(inheritedLabel);
  await expect(rows.last().getByLabel(/Destination URL/)).toHaveValue(fastDestination);
  const before = await markDocument(browser);
  await screen.getByRole("button", "Save draft", { exact: true }).tap();
  await expect(browser.locator(".editor-save-status")).toContainText("Draft saved", { timeout: 30_000 });
  await expectSameDocument(browser, before);
  await app.open(`/admin/businesses/${fixture.businessId}`);
  await browser.locator(".navigator-item").filter({ hasText: "Quick Actions" }).tap();
  expect(await browser.evaluate(labels => labels.map(label => {
    const row = [...document.querySelectorAll('.editor-form-pane .live-item-row')].find(row => row.querySelector<HTMLInputElement>('input[name$=".label"]')?.value === label);
    return row?.querySelector<HTMLInputElement>('input[name$=".url"]')?.value ?? null;
  }), [fastLabel, overrideLabel, inheritedLabel])).toEqual([fastDestination, overrideDestination, fastDestination]);
  const publicationDocument = await markDocument(browser);
  await screen.getByRole("button", "Publish", { exact: true }).tap();
  await expect(browser.locator(".editor-save-status")).toContainText("Published", { timeout: 30_000 });
  await expectSameDocument(browser, publicationDocument);
  await app.open(`/admin/businesses/${fixture.businessId}/preview?page=${fixture.pageId}`);
  await expect(browser.locator(`a[aria-label="${talabatLabel}"]`)).toHaveAttribute("href", destination);
  await expect(browser.locator(`a[aria-label="${fastLabel}"]`)).toHaveAttribute("href", fastDestination);
  await expect(browser.locator(`a[aria-label="${overrideLabel}"]`)).toHaveAttribute("href", overrideDestination);
  await expect(browser.locator(`a[aria-label="${inheritedLabel}"]`)).toHaveAttribute("href", fastDestination);
  expect(await browser.locator(`a[aria-label="${fastLabel}"]`).getAttribute("target")).not.toBe("_blank");
  await app.open(`/b/${fixture.slug}`);
  await expect(browser.locator(`a[aria-label="${talabatLabel}"]`)).toHaveAttribute("href", destination);
  await expect(browser.locator('img[src="/icons/social/fast.png"]').first()).toBeVisible();
  await expect(browser.locator(`a[aria-label="${fastLabel}"]`)).toHaveAttribute("href", fastDestination);
  await expect(browser.locator(`a[aria-label="${overrideLabel}"]`)).toHaveAttribute("href", overrideDestination);
});
