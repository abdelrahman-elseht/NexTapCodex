import { test } from "@e2e-dev/web";
import { credentials, expect } from "e2e";
import { markDocument, expectSameDocument } from "./_helpers/document";

test("single, selected and whole-batch deletion preserve the document and empty exports", async ({ app, screen, browser }) => {
  test.skip(process.env.E2E_ALLOW_MUTATIONS !== "true", "Requires authorized synthetic mutations");
  await app.open("/login?lang=en");
  await screen.getByLabel("Email address").fill(credentials.user("owner").username);
  await screen.getByLabel("Password").fill(credentials.user("owner").password);
  await screen.getByRole("button", "Sign in securely").tap();
  await expect(browser).toHaveURL(/\/admin(?:\?.*)?$/);
  await app.open("/admin/cards");
  await browser.locator('input[name="name"]').fill(`Inventory deletion ${Date.now().toString(36)}`);
  await browser.locator('input[name="quantity"]').fill("3");
  await screen.getByRole("button", "إنشاء دفعة", { exact: true }).tap();
  await expect(browser).toHaveURL(/\/admin\/cards\/batches\/[0-9a-f-]+/);
  const batchId = await browser.evaluate(() => location.pathname.split("/").at(-1)!);
  await app.open(`/admin/cards?batch=${batchId}`);
  await expect(browser.locator("tr[data-card-id]")).toHaveCount(3);
  const before = await markDocument(browser);
  await browser.locator("tr[data-card-id]").first().getByRole("button", "حذف البطاقة نهائياً").tap();
  const dialog = browser.locator("dialog[open]");
  await expect(dialog.getByRole("button", "إلغاء")).toBeFocused();
  await dialog.getByRole("button", "إلغاء").tap();
  await expect(browser.locator("tr[data-card-id]")).toHaveCount(3);
  await browser.locator("tr[data-card-id]").first().getByRole("button", "حذف البطاقة نهائياً").tap();
  await dialog.getByLabel("أوافق على حذف البطاقات وسجل تعيينها نهائياً.").check();
  await dialog.getByRole("button", "حذف نهائي", { exact: true }).tap();
  await expect(browser.locator("tr[data-card-id]")).toHaveCount(2);
  await expectSameDocument(browser, before);
  await browser.locator('tr[data-card-id] input[type="checkbox"]').nth(0).check();
  await browser.locator('tr[data-card-id] input[type="checkbox"]').nth(1).check();
  await screen.getByRole("button", "حذف المحدد نهائياً").tap();
  await dialog.getByLabel("أوافق على حذف البطاقات وسجل تعيينها نهائياً.").check();
  await dialog.getByRole("button", "حذف نهائي", { exact: true }).tap();
  await expect(browser.locator("tr[data-card-id]")).toHaveCount(0);
  await expectSameDocument(browser, before);
  const emptyStatus = await browser.evaluate(async id => (await fetch(`/admin/cards/export?batch=${id}`)).status, batchId);
  expect(emptyStatus).toBe(409);
  await app.open(`/admin/cards/batches/${batchId}`);
  await expect(screen.getByRole("button", "لا توجد بطاقات للتنزيل")).toBeDisabled();
  const emptyDocument = await markDocument(browser);
  await screen.getByRole("button", "حذف الدفعة نهائياً").tap();
  const code = await browser.locator('dialog[open] span[dir="ltr"]').textContent();
  await dialog.getByLabel("اكتب رمز الدفعة للتأكيد").fill(code!.replace("·", "").trim());
  await dialog.getByLabel("أوافق على حذف البطاقات وسجل تعيينها نهائياً.").check();
  await dialog.getByRole("button", "حذف نهائي", { exact: true }).tap();
  await expect(browser).toHaveURL("/admin/cards");
  await expectSameDocument(browser, emptyDocument);
  expect(await browser.evaluate(async id => (await fetch(`/admin/cards/export?batch=${id}`)).status, batchId)).toBe(404);
});
